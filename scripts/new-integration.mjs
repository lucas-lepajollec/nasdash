#!/usr/bin/env node
/**
 * The integration kit's generator: writes the skeleton of a new service
 * integration and its widget, and lists it everywhere NasDash needs it.
 *
 *   npm run new:integration -- <id> --name "Display name" --section <section> \
 *     --widget <widget-type> --guide machines|docker|network [--group <widget group>]
 *   npm run new:integration -- <id> --name "Display name" --into <existing section>
 *
 * The first form creates a new family: a Settings → Integrations section, a
 * widget and its setup guide. `--into` adds another provider to an existing
 * family (its collector answers the family's summary). Then:
 *
 *   1. fill `src/integrations/<id>/samples/service.json` with a real answer
 *      (private data removed) and write `collect.ts` against it;
 *   2. translate the generated messages file and run `node scripts/i18n-add.mjs <file>`;
 *   3. add a connection and the widget to `demo/fixtures` (a test checks every widget is in the demo);
 *   4. `npm run check:i18n`, `npx tsc --noEmit`, `npx vitest run src/integrations`.
 *
 * See `src/integrations/README.md` → "The integration kit".
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';

const root = process.cwd();
const args = process.argv.slice(2);
const id = args.find(value => !value.startsWith('--') && !args[args.indexOf(value) - 1]?.startsWith('--'));
const option = name => { const index = args.indexOf(`--${name}`); return index >= 0 ? args[index + 1] : undefined; };
const fail = message => { console.error(message); process.exit(1); };

const name = option('name');
const into = option('into');
const section = into ?? option('section');
const widget = option('widget');
const guide = option('guide');
const group = option('group') ?? (guide === 'docker' ? 'docker' : guide === 'machines' ? 'system' : 'network');

if (!id || !/^[a-z]+$/.test(id)) fail('The integration id is lowercase letters only, e.g. `npm run new:integration -- uptimekuma --name "Uptime Kuma" …`.');
if (!name) fail('--name "Display name" is required.');
if (!section || !/^[a-z]+$/.test(section)) fail('--section (or --into) is lowercase letters only.');
if (!into) {
  if (!widget || !/^[a-z][a-z0-9-]{1,40}$/.test(widget)) fail('--widget is the new widget type, e.g. `uptime`.');
  if (!['machines', 'docker', 'network'].includes(guide)) fail('--guide is machines, docker or network (the first-start family).');
  if (!['services', 'system', 'docker', 'network', 'media', 'music', 'downloads', 'content', 'gadgets'].includes(group)) fail('--group is a widget library group.');
}

const path = file => join(root, file);
const read = file => readFileSync(path(file), 'utf8');
const camel = id;
const pascal = (value => value.split(/[-_]/).map(part => part[0].toUpperCase() + part.slice(1)).join(''))(into ? id : widget);
const summary = `${into ? '' : pascal}Summary`;

const kit = read('src/integrations/kit.ts');
// The section is letters only (checked above); escaped anyway, as any text put in a pattern.
const escaped = section.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const existing = new RegExp(`\\{ section: '${escaped}', widget: '([^']+)', types: \\[([^\\]]*)\\]`).exec(kit);
if (into && !existing) fail(`No kit family has the section "${section}".`);
if (!into && existing) fail(`The section "${section}" exists already: use --into ${section} to add a provider to it.`);
if (existsSync(path(`src/integrations/${id}`))) fail(`src/integrations/${id} exists already.`);
if (!into && existsSync(path(`src/widgets/${widget}`))) fail(`src/widgets/${widget} exists already.`);
if (read('src/integrations/registry.ts').includes(`id: '${id}'`) || existsSync(path(`src/integrations/${id}/manifest.ts`))) fail(`${id} is already an integration.`);

const written = [];
const write = (file, content) => {
  mkdirSync(dirname(path(file)), { recursive: true });
  writeFileSync(path(file), content);
  written.push(file);
};
const patch = (file, marker, insert) => {
  const source = read(file);
  if (!source.includes(marker)) fail(`${file}: the marker "${marker}" is missing; add the line by hand.`);
  // Inline markers (`/* … */`) take the new entry just before them; line markers keep their own line below it.
  const inline = marker.startsWith('/*');
  writeFileSync(path(file), source.replace(marker, inline ? `${insert}${marker}` : `${insert}\n${marker.match(/^\s*/)[0]}${marker.trimStart()}`));
  if (!written.includes(file)) written.push(file);
};

// The summary contract: a new family gets its own; a provider added to a family answers the family's.
const familySummary = into ? /KitServer<(\w+)>/.exec(read(`src/integrations/${existing[2].split(',')[0].trim().replace(/'/g, '')}/collect.ts`))?.[1] : summary;
if (!into) {
  writeFileSync(path('src/lib/widgetData/contracts.ts'), `${read('src/lib/widgetData/contracts.ts').trimEnd()}

/** ${name}: what the ${widget} widget shows. Generated by \`npm run new:integration\`: describe the real fields. */
export interface ${summary} extends KitSummaryBase {
  provider: '${id}';
  items: { name: string; value: number }[];
}
`);
  written.push('src/lib/widgetData/contracts.ts');
}

write(`src/integrations/${id}/manifest.ts`, `import type { ServiceIntegrationManifest } from '../types';

export const ${camel}Manifest: ServiceIntegrationManifest = {
  id: '${id}',
  name: ${JSON.stringify(name)},
  // A logo of the dashboard-icons collection (svg/…svg or png/…png), checked to exist.
  logo: 'svg/${id}.svg',
  fields: [
    { id: 'url', kind: 'text', required: true, label: 'integrations.${id}.url', placeholder: 'http://${id}.example.com' },
    { id: 'apiKey', kind: 'secret', required: true, label: 'integrations.${id}.apiKey' },
    { id: 'allowSelfSigned', kind: 'toggle', label: 'integrations.allowSelfSigned' },
  ],
};
`);

write(`src/integrations/${id}/samples/service.json`, `{
  "items": [
    { "name": "Example", "value": 42 }
  ]
}
`);

write(`src/integrations/${id}/collect.ts`, `import type { IntegrationInstance } from '@/lib/types';
import type { ${familySummary} } from '@/lib/widgetData/contracts';
import { array, number, object, serviceJson, string, ServiceError } from '@/lib/widgetData/services';
import type { KitServer } from '../kitServer';

/**
 * ${name}. Generated by \`npm run new:integration\`: replace the path, the
 * authentication header and the mapping with the service's real API, written
 * against \`samples/service.json\` (a real answer, private data removed).
 * Read only, unless an action is declared below.
 */
export const ${camel}Request = <T = unknown>(instance: IntegrationInstance, path: string) =>
  serviceJson<T>(instance, path, { headers: { 'X-API-Key': instance.secrets?.apiKey ?? '' } });

export function to${pascal}(instance: IntegrationInstance, answer: unknown, now = Date.now()): ${familySummary} {
  const list = object(answer).items;
  if (!Array.isArray(list)) throw new ServiceError('widgets.error.parse');
  return {
    provider: '${id}', name: instance.name,
    items: array(list).map(object).map(item => ({ name: string(item.name).slice(0, 120), value: number(item.value) })),
    fetchedAt: now,
  }${into ? ' as unknown as ' + familySummary : ''};
}

export const ${camel}Kit: KitServer<${familySummary}> = {
  // How long one reading is shared by every widget on this connection.
  ttlMs: 60_000,
  collect: async instance => to${pascal}(instance, await ${camel}Request(instance, '/api/TODO')),
  test: async instance => { await ${camel}Request(instance, '/api/TODO'); },
  // The public demo: invented values, documentation addresses only.
  demo: instance => to${pascal}(instance, { items: [{ name: 'Example', value: 42 }] }),
};
`);

write(`src/integrations/${id}/collect.test.ts`, `import { beforeEach, describe, expect, it, vi } from 'vitest';
import type { IntegrationInstance } from '@/lib/types';
vi.mock('@/lib/widgetData/services', async original => ({ ...await original<typeof import('@/lib/widgetData/services')>(), serviceJson: vi.fn() }));
import { serviceJson, ServiceError } from '@/lib/widgetData/services';
import { ${camel}Kit, to${pascal} } from './collect';
import sample from './samples/service.json';

const json = vi.mocked(serviceJson);
const source: IntegrationInstance = { id: '${id}-1', type: '${id}', name: ${JSON.stringify(name)}, settings: { url: 'http://${id}.example.com' }, secrets: { apiKey: 'fake-key' } };
beforeEach(() => vi.resetAllMocks());

describe(${JSON.stringify(name)}, () => {
  it('maps a real answer', async () => {
    json.mockResolvedValue(sample);
    expect(await ${camel}Kit.collect(source)).toMatchObject({ provider: '${id}', name: ${JSON.stringify(name)} });
    expect(json.mock.calls[0][2]?.headers).toEqual({ 'X-API-Key': 'fake-key' });
  });
  it('fails clearly on an answer that is not this service', () => {
    expect(() => to${pascal}(source, { message: 'not found' })).toThrow(ServiceError);
  });
});
`);

if (!into) {
  write(`src/widgets/${widget}/definition.ts`, `import { defineWidget } from '../define';

export default defineWidget({
  type: '${widget}', group: '${group}', icon: '🧩',
  nameKey: 'widget.${widget}.name', descriptionKey: 'widget.${widget}.description',
  // What the service tells about the installation: viewers need their own permission.
  access: { permission: '${widget}' },
  // Widths it can be resized to (columns out of 24), width when added,
  // smallest usable width (px) and typical height (px) before measuring.
  sizes: { formats: [4, 6, 8, 12], default: 6, minPx: 180, h: 220 },
});
`);
  write(`src/widgets/${widget}/view.tsx`, `import { WidgetContainer } from '@/components/widgets/WidgetContainer';
import type { WidgetViewProps } from '../types';
import Calme${pascal} from './Calme${pascal}';

export default function ${pascal}View({ instance, editMode, isVisible, onUpdateSettings }: WidgetViewProps) {
  return <WidgetContainer><Calme${pascal} widgetId={instance.id} settings={instance.settings} editMode={editMode} isVisible={isVisible} onUpdateSettings={onUpdateSettings} /></WidgetContainer>;
}
`);
  write(`src/widgets/${widget}/Calme${pascal}.tsx`, `'use client';

import React from 'react';
import type { WidgetSettings } from '@/lib/pages/types';
import type { ${summary} } from '@/lib/widgetData/contracts';
import { KitWidget } from '@/components/widgets/content/KitWidget';

/** ${name}. Generated by \`npm run new:integration\`: draw what matters, with the kit's classes (\`ndw-kit-*\`). */
export default function Calme${pascal}(props: { widgetId: string; settings: WidgetSettings; editMode: boolean; isVisible: boolean; onUpdateSettings: (settings: WidgetSettings) => void }) {
  return (
    <KitWidget<${summary}> widget="${widget}" refreshMs={60_000} {...props}>
      {data => (
        <div className="ndw-kit">
          <ul className="ndw-kit-list">
            {data.items.map(item => (
              <li key={item.name} className="ndw-kit-row">
                <span className="ndw-kit-row-head"><span className="ndw-kit-row-name">{item.name}</span><span className="ndw-kit-row-value">{item.value}</span></span>
              </li>
            ))}
          </ul>
        </div>
      )}
    </KitWidget>
  );
}
`);
}

// Listed everywhere NasDash reads them.
patch('src/integrations/registry.ts', '// new:integration manifests', `import { ${camel}Manifest } from './${id}/manifest';`);
patch('src/integrations/registry.ts', '/* new:integration list */', `${camel}Manifest, `);
patch('src/integrations/kitServer.ts', '// new:integration imports', `import { ${camel}Kit } from './${id}/collect';`);
patch('src/integrations/kitServer.ts', '  // new:integration servers', `  ${camel}: ${camel}Kit,`);
if (into) {
  const source = read('src/integrations/kit.ts');
  writeFileSync(path('src/integrations/kit.ts'), source.replace(existing[0], `{ section: '${section}', widget: '${existing[1]}', types: [${existing[2]}, '${id}']`));
  written.push('src/integrations/kit.ts');
} else {
  patch('src/integrations/kit.ts', '  // new:integration families', `  { section: '${section}', widget: '${widget}', types: ['${id}'], guide: '${guide}' },`);
  patch('src/widgets/definitions.ts', '// new:integration definitions', `import ${camel}Widget from './${widget}/definition';`);
  patch('src/widgets/definitions.ts', '  // new:integration widgets', `  ${camel}Widget,`);
  patch('src/widgets/views.ts', '// new:integration views', `import ${camel}View from './${widget}/view';`);
  patch('src/widgets/views.ts', '  // new:integration view entries', `  '${widget}': ${camel}View,`);
}

// Interface texts to translate, then add with scripts/i18n-add.mjs.
const todo = language => `TODO (${language})`;
const texts = english => [english, todo('fr'), todo('es'), todo('de'), todo('it')];
const messages = {
  [`integrations.info.${id}`]: texts(`${name}, with an API key that reads what the widget shows.`),
  [`integrations.${id}.url`]: texts(`${name} address`),
  [`integrations.${id}.apiKey`]: texts('API key'),
  ...(into ? {} : {
    [`widget.${widget}.name`]: texts(name),
    [`widget.${widget}.description`]: texts(`${name}: what it shows.`),
    [`integrations.${section}`]: texts(name),
    [`integrations.${section}Hint`]: texts(`${name}, for the ${name} widget.`),
    [`integrations.${section}Empty`]: texts(`No ${name} connected.`),
    [`setup.${section}.title`]: texts(`To show ${name}`),
    [`setup.${section}.connect`]: texts(`Connect ${name}`),
    [`setup.${section}.connectAction`]: texts('Integrations'),
  }),
};
const messagesFile = `.project-local/new-integration/${id}.messages.json`;
mkdirSync(dirname(path(messagesFile)), { recursive: true });
writeFileSync(path(messagesFile), `${JSON.stringify(messages, null, 2)}\n`);

console.log(`${name} (${id}) added to the integration kit.\n\nWritten or updated:\n${written.map(file => `  ${file}`).join('\n')}\n`);
console.log(`Next:
  1. Save a real answer in src/integrations/${id}/samples/service.json and write src/integrations/${id}/collect.ts against it.
  2. Translate ${relative(root, path(messagesFile))} (en, fr, es, de, it), then: node scripts/i18n-add.mjs ${messagesFile}
  3. Add a connection${into ? '' : ' and the widget'} to demo/fixtures (config.json integrations, pages.json).
  4. Check: npm run check:i18n && npx tsc --noEmit && npx vitest run src/integrations src/widgets src/lib/demoFixtures.test.ts
  5. Document it (docs repository: content/docs/integrations, five languages) and in CHANGELOG.md.`);
